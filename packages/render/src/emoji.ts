export interface EmojiMatch {
  glyph: string;
  name: string;
}

/**
 * Prefix-first fuzzy search: exact-name prefix beats name substring beats
 * keyword word-prefix beats keyword substring; ties keep curated order.
 * Queries under 2 chars return nothing (the `:` trigger opens only after two).
 */
export function searchEmojis(query: string, max = 7): EmojiMatch[] {
  const q = query.toLowerCase();
  if (q.length < 2) return [];
  const scored: Array<{ rank: number; i: number; m: EmojiMatch }> = [];
  for (let i = 0; i < EMOJI.length; i++) {
    const entry = EMOJI[i];
    if (!entry) continue;
    const [glyph, name, kw] = entry;
    let rank = -1;
    if (name.startsWith(q)) rank = 0;
    else if (name.includes(q)) rank = 1;
    else if (kw.split(" ").some((w) => w.startsWith(q))) rank = 2;
    else if (kw.includes(q)) rank = 3;
    if (rank >= 0) scored.push({ rank, i, m: { glyph, name } });
  }
  scored.sort((a, b) => a.rank - b.rank || a.i - b.i);
  return scored.slice(0, max).map((s) => s.m);
}
