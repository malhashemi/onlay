// The "Bundled packages" part of THIRD-PARTY-NOTICES.md, from the bundler's own
// graph of everything Onlay ships.
//
//   bun run notices           rewrite that part of THIRD-PARTY-NOTICES.md
//   bun run notices --check   exit 1 if it is out of date (`bun run check` runs this)
//
// Each artifact is bundled here as its build bundles it (the same entry points,
// targets, formats and externals; nothing is written), and Bun's metafile names
// every module the bundle read. Every module under node_modules belongs to a
// third-party package whose code can end up in the artifact: the table lists
// each such package with the artifacts it is in, and the texts below it are
// each package's own licence and notice files, as the package ships them.
//
// When a build gains or loses an entry point, change ARTIFACTS to match.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, sep } from "node:path";

const ROOT = join(import.meta.dir, "..");
const NOTICES = join(ROOT, "THIRD-PARTY-NOTICES.md");
const BEGIN =
  "<!-- BEGIN bundled packages: generated by `bun run notices` (scripts/notices.ts); do not edit by hand -->";
const END = "<!-- END bundled packages -->";

type Build = {
  entries: string[];
  target: "browser" | "node";
  format?: "esm" | "iife" | "cjs";
  splitting?: boolean;
  external?: string[];
};

const ext = (f: string) => join(ROOT, "packages/extension/src", f);
const stamp = (f: string) => join(ROOT, "packages/stamp/src", f);

/** What each shipped artifact bundles: its build script's Bun.build calls. */
const ARTIFACTS: Record<string, Build[]> = {
  // packages/server: wrangler bundles src/worker.ts (the Durable Object too).
  Worker: [
    {
      entries: [join(ROOT, "packages/server/src/worker.ts")],
      target: "browser",
      external: ["cloudflare:*", "node:*"],
    },
  ],
  // packages/pwa/scripts/build.ts: main.ts (split) and sw.ts.
  "web app": [
    {
      entries: [join(ROOT, "packages/pwa/src/main.ts")],
      target: "browser",
      splitting: true,
    },
    { entries: [join(ROOT, "packages/pwa/src/sw.ts")], target: "browser" },
  ],
  // packages/site/scripts/build.ts: main.ts (split).
  site: [
    {
      entries: [join(ROOT, "packages/site/src/main.ts")],
      target: "browser",
      splitting: true,
    },
  ],
  // packages/extension/scripts/build.ts: sw.ts (ESM) and four classic scripts.
  extension: [
    { entries: [ext("sw.ts")], target: "browser" },
    ...["content.ts", "popup.ts", "options.ts", "interaction.ts"].map(
      (f): Build => ({ entries: [ext(f)], target: "browser", format: "iife" }),
    ),
  ],
  // packages/stamp/scripts/build.ts: one bundle per framework.
  stamp: [
    ...["vite.ts", "next.ts", "svelte.ts"].map(
      (f): Build => ({ entries: [stamp(f)], target: "node" }),
    ),
    {
      entries: [stamp("astro.ts")],
      target: "node",
      external: ["@astrojs/compiler", "@astrojs/compiler-rs"],
    },
    { entries: [stamp("next-loader.ts")], target: "node", format: "cjs" },
  ],
};

interface Pkg {
  name: string;
  version: string;
  license: string;
  author: string;
  dir: string;
  artifacts: Set<string>;
}

