/** The package directory a bundled module path lies in, or null for our own code. */
function packageDirOf(path: string): string | null {
  const parts = path.split(sep);
  const at = parts.lastIndexOf("node_modules");
  if (at < 0) return null;
  const name = parts[at + 1] ?? "";
  const depth = name.startsWith("@") ? at + 3 : at + 2;
  return parts.slice(0, depth).join(sep);
}

async function bundledPackages(): Promise<Pkg[]> {
  const found = new Map<string, Pkg>();
  for (const [artifact, builds] of Object.entries(ARTIFACTS)) {
    for (const b of builds) {
      const result = await Bun.build({
        entrypoints: b.entries,
        target: b.target,
        format: b.format ?? "esm",
        ...(b.splitting ? { splitting: true } : {}),
        ...(b.external ? { external: b.external } : {}),
        metafile: true,
      });
      if (!result.success) {
        console.error(result.logs.join("\n"));
        throw new Error(`notices: bundling ${b.entries.join(", ")} failed`);
      }
      const inputs = Object.keys(result.metafile?.inputs ?? {});
      if (inputs.length === 0) throw new Error(`notices: no metafile for ${b.entries.join(", ")}`);
      for (const input of inputs) {
        const dir = packageDirOf(join(ROOT, input));
        if (!dir) continue;
        const manifest = JSON.parse(readFileSync(join(dir, "package.json"), "utf8")) as {
          name: string;
          version: string;
          license?: string;
          author?: string | { name?: string };
        };
        const key = `${manifest.name}@${manifest.version}`;
        const pkg = found.get(key) ?? {
          name: manifest.name,
          version: manifest.version,
          license: manifest.license ?? "(none declared)",
          author:
            (typeof manifest.author === "string" ? manifest.author : manifest.author?.name) ?? "",
          dir,
          artifacts: new Set<string>(),
        };
        pkg.artifacts.add(artifact);
        found.set(key, pkg);
      }
    }
  }
  return [...found.values()].sort(
    (a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version),
  );
}

/** The package's own licence and notice files, in name order. */
function legalFiles(dir: string): string[] {
  return readdirSync(dir)
    .filter((f) => /^(licen[cs]e|copying|notice)(\.|$|-)/i.test(f))
    .sort()
    .map((f) => readFileSync(join(dir, f), "utf8").replace(/\r\n/g, "\n").trim());
}

function fence(text: string): string {
  const longest = Math.max(2, ...[...text.matchAll(/`+/g)].map((m) => m[0].length));
  const ticks = "`".repeat(longest + 1);
  return `${ticks}text\n${text}\n${ticks}`;
}

function render(pkgs: Pkg[]): string {
  const order = Object.keys(ARTIFACTS);
  const rows = pkgs.map((p) => {
    const where = order.filter((a) => p.artifacts.has(a)).join(", ");
    return `| \`${p.name}\` | ${p.version} | ${p.license} | ${where} |`;
  });
  // One text, once: packages that ship the same files share a heading.
  const byText = new Map<string, string[]>();
  for (const p of pkgs) {
    const files = legalFiles(p.dir);
    if (files.length === 0 && p.license !== "MIT")
      throw new Error(`notices: ${p.name} ${p.version} ships no licence file and is not MIT`);
    // No file of its own: the MIT terms its package.json declares, under its author.
    const text =
      files.length > 0
        ? files.join("\n\n")
        : `(No licence file in the package; its package.json declares MIT${p.author ? `, by ${p.author}` : ""}.)\n\nMIT License\n\nCopyright (c) ${p.author || `the ${p.name} authors`}\n\n${MIT_TERMS}`;
    byText.set(text, [...(byText.get(text) ?? []), `\`${p.name}\` ${p.version}`]);
  }
  const texts = [...byText.entries()].map(
    ([text, names]) => `#### ${names.join(", ")}\n\n${fence(text)}`,
  );
  return [
    BEGIN,
    "## Bundled packages",
    "",
    "The code of these packages is bundled into what Onlay ships: the Worker",
    "(`app.onlay.dev`, and any deployment of this repository), the web app at",
    "`/app/`, the landing page, the extension and the stamp tarball. The list is",
    "made from each build's own module graph. The licence and notice texts below",
    "are each package's own files.",
    "",
    "| Package | Version | Licence | In |",
    "|---|---|---|---|",
    ...rows,
    "",
    "### Licence and notice texts",
    "",
    texts.join("\n\n"),
    END,
  ].join("\n");
}

const pkgs = await bundledPackages();
const section = render(pkgs);
const current = readFileSync(NOTICES, "utf8");
const begin = current.indexOf(BEGIN);
const end = current.indexOf(END);
if (begin < 0 || end < begin) throw new Error(`notices: ${NOTICES} has no generated section`);
const next = `${current.slice(0, begin)}${section}${current.slice(end + END.length)}`;

if (process.argv.includes("--check")) {
  if (next !== current) {
    console.error(
      "THIRD-PARTY-NOTICES.md is out of date with what the builds bundle: run `bun run notices`.",
    );
    process.exit(1);
  }
  console.log(`THIRD-PARTY-NOTICES.md lists all ${pkgs.length} bundled packages.`);
} else {
  writeFileSync(NOTICES, next);
  console.log(`THIRD-PARTY-NOTICES.md: ${pkgs.length} bundled packages.`);
}
